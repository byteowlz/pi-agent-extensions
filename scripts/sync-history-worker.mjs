import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const sources = ["config.ts", "indexer.ts", "operations.ts", "recall.ts", "worker-entry.ts"];
const hash = createHash("sha256");
for (const name of sources) hash.update(`${name}\0${readFileSync(join(root, "pi-history-search", name), "utf8")}\0`);
const marker = `// Generated by scripts/sync-history-worker.mjs; sources-sha256=${hash.digest("hex")}`;
const output = join(root, "pi-history-search/worker-runtime.mjs");
if (process.argv.includes("--check")) {
	const artifact = readFileSync(output, "utf8");
	if (!artifact.startsWith(`${marker}\n`))
		throw new Error("History worker artifact is stale; run node scripts/sync-history-worker.mjs");
} else {
	const result = spawnSync(
		"bun",
		["build", "pi-history-search/worker-entry.ts", "--target=node", "--format=esm", `--outfile=${output}`],
		{ cwd: root, stdio: "inherit" }
	);
	if (result.status !== 0) throw new Error("History worker build failed (Bun is required for maintenance, not for runtime)");
	writeFileSync(output, `${marker}\n${readFileSync(output, "utf8")}`);
}
