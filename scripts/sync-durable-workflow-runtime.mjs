#!/usr/bin/env node
// Deployment is a copied extension directory. Keep the portable source canonical,
// but ship deterministic local runtime copies instead of ../ sibling imports.
import { readFile, writeFile } from "node:fs/promises";

const header = "// @generated by npm run build:workflow; do not edit independently.\n";
for (const [source, destination] of [
	["../packages/pi-durable-workflow-core/index.ts", "../pi-durable-workflow/core.ts"],
	["../pi-session-tools/output-budget.ts", "../pi-durable-workflow/output-budget.ts"],
]) {
	const contents = await readFile(new URL(source, import.meta.url), "utf8");
	await writeFile(new URL(destination, import.meta.url), header + contents);
}
