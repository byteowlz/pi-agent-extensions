/**
 * Per-run staging for a sandboxed history rewrite.
 *
 * Layout (root 0700):
 *   policy.toml           0600, outside the workspace grant
 *   work/                 the ONLY --workspace grant
 *     session.jsonl       0600 copy that the surgeon may change
 *     agent/              private PI_CODING_AGENT_DIR (models/auth copied)
 *     sessions/           the surgeon's own --session-dir
 *     home/               HOME
 *     ext/                copied extension folder the child loads
 */

import {
	chmodSync,
	copyFileSync,
	cpSync,
	existsSync,
	mkdirSync,
	mkdtempSync,
	readFileSync,
	rmSync,
	statSync,
	writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { basename, join } from "node:path";

export interface StagingOptions {
	/** The session file to copy; never modified in place. */
	sourceFile: string;
	/** Directory holding the parent's models.json/auth.json. */
	agentDir: string;
	/** This extension's directory, copied so the child can load it. */
	extensionDir: string;
	/** Optional explicit temp root (tests). */
	root?: string;
}

export interface Staging {
	root: string;
	/** The sole `--workspace` grant. */
	work: string;
	agentDir: string;
	sessionsDir: string;
	homeDir: string;
	extDir: string;
	extEntry: string;
	policyPath: string;
	targetFile: string;
	originalFile: string;
	cleanup(): void;
}

const PRIVATE_DIR = 0o700;
const PRIVATE_FILE = 0o600;

function ensurePrivateDir(path: string): void {
	mkdirSync(path, { recursive: true, mode: PRIVATE_DIR });
	chmodSync(path, PRIVATE_DIR);
}

function copyPrivate(from: string, to: string): void {
	copyFileSync(from, to);
	chmodSync(to, PRIVATE_FILE);
}

/**
 * Restriction-only overlay. Only `deny_*` and a lowered `home_access` are
 * allowed by oqto-sandbox; no grants, no bind additions, no profile change.
 * Network is inherited (the surgeon must reach the model provider).
 */
export function overlayToml(denyPaths: readonly string[] = DEFAULT_DENY_PATHS): string {
	const list = (paths: readonly string[]) => `[${paths.map((path) => JSON.stringify(path)).join(", ")}]`;
	return [
		"# Generated by pi-session-surgeon; restriction-only overlay (ADR 0070).",
		`deny_read = ${list(denyPaths)}`,
		`deny_write = ${list(denyPaths)}`,
		'home_access = "none"',
		"",
	].join("\n");
}

/** Parent agent state and credentials the child must not reach. */
export const DEFAULT_DENY_PATHS = ["~/.pi", "~/.ssh", "~/.aws", "~/.gnupg", "~/.config/gh", "~/.kube"] as const;

export function createStaging(options: StagingOptions): Staging {
	const source = statSync(options.sourceFile);
	if (!source.isFile()) throw new Error(`not a regular session file: ${options.sourceFile}`);
	const root = options.root ?? mkdtempSync(join(tmpdir(), "pi-surgeon-"));
	ensurePrivateDir(root);
	const work = join(root, "work");
	ensurePrivateDir(work);
	const agent = join(work, "agent");
	ensurePrivateDir(agent);
	const sessions = join(work, "sessions");
	ensurePrivateDir(sessions);
	const home = join(work, "home");
	ensurePrivateDir(home);
	const extDir = join(work, "ext", "pi-session-surgeon");
	mkdirSync(join(work, "ext"), { recursive: true, mode: PRIVATE_DIR });
	cpSync(options.extensionDir, extDir, { recursive: true });

	// Private agent dir: only what Pi needs to talk to the model.
	for (const file of ["models.json", "auth.json"]) {
		const from = join(options.agentDir, file);
		if (existsSync(from)) copyPrivate(from, join(agent, file));
	}

	const targetFile = join(work, "session.jsonl");
	copyPrivate(options.sourceFile, targetFile);
	const policyPath = join(root, "policy.toml");
	writeFileSync(policyPath, overlayToml(), { mode: PRIVATE_FILE });
	chmodSync(policyPath, PRIVATE_FILE);

	return {
		root,
		work,
		agentDir: agent,
		sessionsDir: sessions,
		homeDir: home,
		extDir,
		extEntry: join(extDir, "index.ts"),
		policyPath,
		targetFile,
		originalFile: options.sourceFile,
		cleanup: () => {
			try {
				rmSync(root, { recursive: true, force: true });
			} catch {
				/* best effort */
			}
		},
	};
}

/** Read back the target so callers can verify/diff without touching staging internals. */
export function readStagedSession(staging: Staging): string {
	return readFileSync(staging.targetFile, "utf8");
}

export function stagedName(staging: Staging): string {
	return basename(staging.originalFile);
}
